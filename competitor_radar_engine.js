class CompetitorRadarEngine {
  isRadarRequest(text) {
    if (!text) return false;
    const t = text.toLowerCase();
    return t.includes('מתחרים') || 
           t.includes('סרוק מתחרים') || 
           t.includes('דוח שוק') || 
           t.includes('ריגול מודעות') || 
           t.includes('ניתוח שוק') ||
           t.includes('בדיקת מתחרים');
  }

  generateRadarReport(topicOrNiche) {
    const cleanTopic = (topicOrNiche || 'שיווק דיגיטלי ופיתוח עסקי')
      .replace(/^(?:סרוק מתחרים של|דוח שוק ב|ריגול מודעות ב|ניתוח שוק של|בדיקת מתחרים)\s*/i, '')
      .trim();

    return `📊 *דו"ח מודיעין שוק ומתחרים: ${cleanTopic}* 🔸

1. 🔍 *מפת האיומים והמתחרים בשוק הישראלי:*
   - רוב המתחרים בתחום מציעים פתרונות גנריים ("קמפיין בפייסבוק" או "אתר וורדפרס בסיסי") ללא אינטגרציה עסקית אמיתית.
   - *היתרון והבידול של GOR MARKETING:* שילוב של סוכני AI ואוטומציה, עיצוב פרימיום מודרני, וחיבור ישיר למערכת CRM מותאמת אישית.

2. 📢 *זוויות קריאייטיב ומודעות מובילות (Meta & Google Ads):*
   - *זווית פחד מהחמצה / הפסד:* "כמה כסף העסק שלך מפסיד בכל חודש על לידים שלא חוזרים אליהם תוך 5 דקות?"
   - *זווית תוצאה ושקט נפשי:* "במקום עוד ספק שמבטיח הבטחות באוויר – צוות מומחים מוביל מ-2008 שמביא תוצאות בשטח."
   - *זווית סמכות וטכנולוגיה:* "שילוב מערכות בינה מלאכותית ואוטומציה שחוסכות 15 שעות עבודה שבועיות."

3. 💰 *מחירוני שוק מקובלים (בנצ'מרק 2026):*
   - ניהול קמפיין ממומן בסיסי: 2,500 - 4,500 ₪ / חודש.
   - מעטפת שיווק פרימיום מלאה (קמפיינים + SEO + אוטומציות): 6,000 - 12,000 ₪ / חודש.
   - הקמת אתרי תדמית / חנויות סחר: 6,000 - 25,000 ₪ (תלוי מורכבות).

4. 🚀 *המלצת תקיפה שיווקית מיידית:*
   - יצירת הצעת ערך בלתי ניתנת לסירוב: *"הקמת מערך שיווק וסוכני AI עם ליווי שטח מלא"*.
   - קמפיין ממוקד Google Search + רימרקטינג באינסטגרם/פייסבוק.`;
  }
}

module.exports = new CompetitorRadarEngine();
